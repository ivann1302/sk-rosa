function cityHash(slug) {
  return [...slug].reduce((value, char) => (value * 31 + char.charCodeAt(0)) % 9973, 7);
}

export function getBiozashchitaCityTemplate(citySlug) {
  return templates[cityHash(citySlug) % templates.length];
}
