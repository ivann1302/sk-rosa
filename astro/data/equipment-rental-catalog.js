function copyParts(copy) {
  const splitAt = copy.indexOf(". ");

  return {
    purpose: copy.slice(0, splitAt + 1),
    selection: copy.slice(splitAt + 2),
  };
}

export function russianPlural(count, one, few, many) {
  const modulo100 = Math.abs(count) % 100;
  const modulo10 = modulo100 % 10;

  if (modulo100 >= 11 && modulo100 <= 14) return many;
  if (modulo10 === 1) return one;
  if (modulo10 >= 2 && modulo10 <= 4) return few;

  return many;
}

function absoluteUrl(pathname) {
  return new URL(pathname, "https://sk-rosa.ru").href;
}

function categoryPath(categorySlug) {
  return `${categoryRoot}/${categorySlug}`;
}

const detailedCatalogItems = rentalEquipment.map(item => ({
  ...item,
  catalogHref: `/${item.slug}`,
}));

const importedCatalogItems = rentalCatalogEquipment.map(item => ({
  ...item,
  catalogHref: `${categoryPath(item.categorySlug)}#${item.slug}`,
}));

export const catalogRentalEquipment = [...detailedCatalogItems, ...importedCatalogItems];

const categorySeeds = new Map();

for (const item of importedCatalogItems) {
  const key = `${item.groupSlug}:${item.categorySlug}`;

  if (!categorySeeds.has(key)) {
    categorySeeds.set(key, item);
  }
}

export const rentalCategoryPages = [...categorySeeds.values()]
  .map(seed => {
    const items = catalogRentalEquipment.filter(
      item => item.group === seed.group && item.categorySlug === seed.categorySlug,
    );
    const publishedPrices = items
      .filter(item => item.catalogEntry && item.availabilityMode !== "unavailable")
      .map(item => item.priceFrom);
    const priceFrom = Math.min(...publishedPrices);
    const pathname = categoryPath(seed.categorySlug);
    const rentalName = categoryRentalNames[seed.categoryName];
    const lead = categorySeoCopy[seed.categoryName];
    const { purpose, selection } = copyParts(lead);

    return {
      slug: seed.categorySlug,
      name: seed.categoryName,
      rentalName,
      serviceType: `Аренда ${rentalName}`,
      group: seed.group,
      groupSlug: seed.groupSlug,
      pathname,
      href: pathname,
      canonical: absoluteUrl(pathname),
      previewImage: seed.previewImage,
      previewImageSize: seed.previewImageSize,
      visualKind: seed.visualKind,
      visualAlt: seed.visualAlt,
      lead,
      task: seed.task,
      useCases: seed.useCases,
      selectionPrompt: selection,
      priceFrom,
      priceLabel: `от ${priceFrom.toLocaleString("ru-RU")} ₽/сутки`,
      items,
      seo: {
        title: `Аренда ${rentalName} — Москва, Долгопрудный | ROSA`,
        description: `${purpose} Аренда в Москве и Долгопрудном — от ${priceFrom.toLocaleString("ru-RU")} ₽/сутки.`,
        canonical: absoluteUrl(pathname),
      },
    };
  })
  .sort((firstCategory, secondCategory) => {
    const groupDifference = groupOrder.indexOf(firstCategory.group) - groupOrder.indexOf(secondCategory.group);

    return groupDifference || firstCategory.name.localeCompare(secondCategory.name, "ru-RU");
  });

